#!/bin/bash
#
# Запускает сервер и печатает его код выхода служебной строкой.
# unbuffer код выхода запущенной программы наружу не передаёт (всегда 0), а
# entrypoint он нужен, чтобы отличить падение от штатного завершения.
# Строку `[cs2-exit] N` entrypoint перехватывает и в консоль не выводит.
#
"$@"
rc=$?
printf '\n[cs2-exit] %s\n' "$rc"
exit "$rc"
